-- 客戶地址簿：讓客戶叫瓦斯時不用每次重打地址
-- 在 Supabase 的 SQL Editor 直接執行即可，重複執行不會出錯。

create table if not exists public.gas_customer_address (
  id bigint generated by default as identity primary key,
  line_uid text not null,
  label text default '',                 -- 客戶自訂名稱，例如「住家」「店面」
  address text not null,
  lat double precision,                  -- 存檔時自動查好的座標，排路線可直接使用
  lng double precision,
  is_default boolean not null default false,
  last_used_at timestamptz,
  created_at timestamptz not null default now(),
  -- 同一位客戶的同一個地址只會有一筆
  constraint gas_customer_address_uid_address_key unique (line_uid, address)
);

create index if not exists gas_customer_address_uid_idx
  on public.gas_customer_address (line_uid, is_default desc, last_used_at desc);

-- 把既有訂單裡出現過的地址一次匯入地址簿（舊客戶也能直接用下拉選單）
-- 座標留空，下次客戶使用該地址下單時會自動補上。
insert into public.gas_customer_address (line_uid, address, last_used_at, created_at)
select distinct on (line_uid, address)
       line_uid, trim(address), max(created_at) over (partition by line_uid, address), now()
  from public.gas_order
 where line_uid is not null
   and address is not null
   and trim(address) <> ''
on conflict (line_uid, address) do nothing;
